import { REACT_APP_SERVER, REACT_APP_API_PORT, REACT_APP_WEB_SOCKET_PORT, REACT_APP_WEBSOCKET, REACT_APP_DOMAIN } from '@env';

export const baseAPIUrl = REACT_APP_DOMAIN
  ? `https://${REACT_APP_DOMAIN}/api`
  : `http://${REACT_APP_SERVER}:${REACT_APP_API_PORT}`;

export const baseWebSocketUrl = REACT_APP_DOMAIN
  ? `wss://${REACT_APP_DOMAIN}/ws`
  : `ws://${REACT_APP_WEBSOCKET}:${REACT_APP_WEB_SOCKET_PORT}`;